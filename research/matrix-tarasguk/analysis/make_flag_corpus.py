#!/usr/bin/env python3
"""formulas/flags-corpus.md: every distinct flag sentence template (numbers masked) with counts, severity, examples; plus below-threshold pairs from 'Відомі ризики'."""
import glob, json, os, re, collections
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
mask = lambda s: re.sub(r'\d+([.,]\d+)?', '#', re.sub(r'\$[\d,]+( млрд| млн| трлн)?', '$#', s))
tpl = collections.OrderedDict()
tables = collections.Counter()
below = collections.Counter(); below_ex = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'cards', '*.json'))):
    c = json.load(open(f, encoding='utf-8'))
    fl = c.get('flags')
    if not fl:
        continue
    t = c['ticker_file']
    for s in fl['sentences']:
        k = mask(s)[:150]
        d = tpl.setdefault(k, {'n': 0, 'ex': []})
        d['n'] += 1
        if len(d['ex']) < 3:
            d['ex'].append((t, s))
    for r in fl['table']:
        if r['severity']:
            tables[(r['flag'], r['severity'], r['points_removed'], r['note'])] += 1
    for s in fl.get('known_risks', []):
        m = re.search(r'\((?:прапорець )?від ([\d,]+ ?(?:%|x))\)', s)
        if m:
            k = re.sub(r'[\d,]+ ?(%|x)', '#', re.sub(r'\([^)]*\)', '', s)).strip()[:80] + ' | threshold ' + m.group(1)
            below[k] += 1
            below_ex.setdefault(k, (t, s))
with open(os.path.join(ROOT, 'formulas', 'flags-corpus.md'), 'w', encoding='utf-8') as o:
    o.write('# Flag corpus (all captured cards, paid tier 2026-10-03)\n\nAuto-generated by `analysis/make_flag_corpus.py`. Numbers masked as `#` in templates; examples keep the original numbers.\n\n## Flag-table rows: (flag, severity, points removed, note) -> number of cards\n')
    for (fl_, sev, pts, note), n in sorted(tables.items(), key=lambda kv: -kv[1]):
        o.write('- %d x | %s | %s | %s | %s\n' % (n, fl_, sev, pts, note))
    o.write('\n## Sentence templates\n')
    for k, d in sorted(tpl.items(), key=lambda kv: -kv[1]['n']):
        o.write('- %d x `%s`\n    - e.g. %s: %s\n' % (d['n'], k, d['ex'][0][0], d['ex'][0][1][:300]))
    o.write('\n## Below-threshold measurements (Known risks) that print the exact threshold\n')
    for k, n in below.most_common():
        o.write('- %d x %s  (e.g. %s: %s)\n' % (n, k, below_ex[k][0], below_ex[k][1][:160]))
print(len(tpl), 'templates;', len(tables), 'table kinds;', len(below), 'threshold lines')
